async function playbackAtOne(page) {
  const result=await page.locator('video').first().evaluate(async v=>{v.currentTime=0;v.playbackRate=1;v.muted=true;await v.play();const start=v.currentTime,at=performance.now();await new Promise(resolve=>setTimeout(resolve,1100));v.pause();return {rate:v.playbackRate,duration:v.duration,advanced:v.currentTime-start,elapsed:(performance.now()-at)/1000}})
  expect(result.rate).toBe(1);expect(result.duration).toBeGreaterThan(2)
  expect(result.advanced/result.elapsed).toBeGreaterThan(.7);expect(result.advanced/result.elapsed).toBeLessThan(1.3)
  return result
}
