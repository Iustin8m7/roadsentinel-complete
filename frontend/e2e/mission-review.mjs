import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage()
  await page.goto(`${process.env.RS_MISSION_UI}/login`)
  await page.locator('input[name="username"]').fill(process.env.RS_MISSION_EMAIL)
  await page.locator('input[name="password"]').fill(process.env.RS_MISSION_PASSWORD)
  await page.getByRole('button', { name: 'Intră', exact: true }).click()
  await page.locator('input[name="code"]').fill(process.env.RS_MISSION_OTP)
  await page.getByRole('button', { name: 'Verifică', exact: true }).click()
  await page.waitForURL('**/app', { timeout: 15000 })
  await page.goto(`${process.env.RS_MISSION_UI}/app/analiza-video`)
  await page.getByLabel('Motivul verificării (minimum 10 caractere)').first().fill('Synthetic recorded fixture: explicit browser resubmission')
  await page.getByRole('button', {name:'Trimite înregistrarea pentru verificare', exact:true}).first().click()
  const review = page.getByRole('link', {name:`RECORDED · deschide alerta #${process.env.RS_MISSION_ALERT}`,exact:true})
  await review.click()
  await page.getByRole('button', {name:'Respinge',exact:true}).click()
  await page.getByLabel('Motiv (obligatoriu)',{exact:true}).fill('SYNTHETIC TEST: frozen licensed frame; no real incident')
  await page.getByRole('button', {name:'Continuă: respinge alerta',exact:true}).click()
  const decision=page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname.endsWith('/decision'))
  await page.getByRole('button', {name:'Respinge alerta',exact:true}).click()
  if((await decision).status()!==200) throw new Error('Browser operator decision was not accepted')
  await page.getByText('Alertă respinsă', { exact: true }).waitFor()
  await page.getByText(/\[SYNTHETIC TEST\]/).first().waitFor()
  await page.getByLabel('Textul notei',{exact:true}).fill('SYNTHETIC TEST: operator browser observation recorded')
  const note=page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname.endsWith('/notes'))
  await page.getByRole('button',{name:'Adaugă nota',exact:true}).click()
  if((await note).status()!==201) throw new Error('Browser case note was not accepted')
  const video = page.locator('video').first()
  await video.waitFor()
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1)
  await page.screenshot({ path: process.env.RS_MISSION_SCREENSHOT, fullPage: true })
  console.log('PASS actual Chromium: password + TOTP, recorded synthetic alert, actual UI rejection and note, protected playable evidence')
} finally { await browser.close() }
